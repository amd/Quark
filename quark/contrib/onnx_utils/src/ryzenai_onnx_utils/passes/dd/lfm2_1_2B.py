def replacement(
    extractor: onnx.utils.Extractor,
    pass_id: str,
    subgraph: list[onnx.NodeProto],
    params: ryzenai_onnx_utils.ReplaceParams,
) -> PassOutputArgs:
    # egregious hack
    last_rmsadd = ryzenai_onnx_utils.matcher.find_nodes_by_input(subgraph[-1].output[0], extractor.graph)[0]
    last_matmul = ryzenai_onnx_utils.matcher.find_nodes_by_input(last_rmsadd.output[1], extractor.graph)[0]
    subgraph.append(last_rmsadd)
    subgraph.append(last_matmul)

    extractor.graph.node.remove(last_rmsadd)
    extractor.graph.node.remove(last_matmul)

    dd_node = build_dd_node(
        extractor,
        subgraph[1:],
        params,
        # extra_outputs=extra_outputs,
        # extra_inputs=["sequence_length"],
    )

    # must match with ModelType enum for Llm_Prefill in dynamic_dispatch.hpp
    ryzenai_onnx_utils.matcher.add_attribute(dd_node, "model_type", int(ModelType.LLM_TOKEN))
    return [subgraph[0], dd_node], [], None


